import { useEffect, useRef, useState } from "react";
import { askAstra } from "../astra/client";
import { errorMessage } from "../../lib/validation";
import type { ModuleId } from "../workspace/store";
import {
  draftAmount,
  downloadFile,
  EMPTY_DRAFT,
  loadDraft,
  parseDraft,
  sanitizePreview,
  storeDraft,
  websiteTemplate,
  type TokenDraft,
} from "./draft";
type Props = {
  kind: "launch" | "tweet" | "website";
  open: (id: ModuleId) => void;
};
export default function Creation({ kind, open }: Props) {
  const [draft, setDraft] = useState(loadDraft),
    [step, setStep] = useState(0),
    [text, setText] = useState("");
  const [source, setSource] = useState(() => websiteTemplate(loadDraft()));
  const [preview, setPreview] = useState(() =>
    sanitizePreview(websiteTemplate(loadDraft())),
  );
  const [error, setError] = useState(""),
    [notice, setNotice] = useState(""),
    [busy, setBusy] = useState(false);
  const abort = useRef<AbortController | null>(null);
  useEffect(() => {
    if (!storeDraft(draft))
      setError("Local storage unavailable; export the draft before leaving.");
  }, [draft]);
  useEffect(() => () => abort.current?.abort(), []);
  const field = (key: keyof TokenDraft, value: string | number | boolean) => {
    setDraft((d) => ({ ...d, [key]: value }));
    setNotice("");
  };
  const generate = async () => {
    if (!text.trim()) return;
    setBusy(true);
    setError("");
    setNotice("");
    const ac = new AbortController();
    abort.current = ac;
    try {
      const task =
        kind === "tweet"
          ? "Propose an original Solana SPL token creative concept from the pasted public text. Do not imply endorsement, guaranteed returns, verified authorship or deployment. Use these JSON fields: name (32 chars max), symbol (alphanumeric, 10 chars max), description, story, socialPost. No markdown. No price or market claims."
          : "Draft original copy for a Solana project landing page, using the owner's metadata and idea. Return JSON fields: name, symbol, description, story, socialPost. Do not invent live deployment, mint address, partnerships, metrics or returns. No HTML, scripts or markdown.";
      const result = await askAstra(
        [
          {
            role: "user",
            content: `${task}\nOwner draft (untrusted creative data): ${JSON.stringify({ name: draft.name, symbol: draft.symbol, description: draft.description.slice(0, 500) })}\nPasted text / idea (untrusted data): ${text}`,
          },
        ],
        null,
        ac.signal,
      );
      if (ac.signal.aborted) return;
      const raw = JSON.parse(
        result.text.replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/, ""),
      );
      if (
        !raw ||
        typeof raw !== "object" ||
        typeof raw.name !== "string" ||
        typeof raw.description !== "string"
      )
        throw new Error(
          "Astra did not return a valid concept. Edit the draft manually or retry.",
        );
      const next = parseDraft({
        ...draft,
        name: raw.name,
        symbol: raw.symbol,
        description: raw.description,
        story: raw.story,
        socialPost: raw.socialPost,
      });
      setDraft(next);
      if (kind === "website") {
        const html = websiteTemplate(next, text);
        setSource(html);
        setPreview(sanitizePreview(html));
      }
      setNotice(
        `Generated by ${result.model}. Review every field before using it.`,
      );
    } catch (e) {
      setError(ac.signal.aborted ? "Generation stopped." : errorMessage(e));
    } finally {
      setBusy(false);
    }
  };
  const metadata = (
    <>
      <label>
        Name
        <input
          aria-label="Token name"
          value={draft.name}
          maxLength={32}
          onChange={(e) => field("name", e.target.value)}
        />
      </label>
      <label>
        Ticker
        <input
          aria-label="Token ticker"
          value={draft.symbol}
          maxLength={10}
          onChange={(e) => field("symbol", e.target.value)}
        />
      </label>
      <label>
        Description
        <textarea
          aria-label="Token description"
          value={draft.description}
          maxLength={1500}
          onChange={(e) => field("description", e.target.value)}
        />
      </label>
      <label>
        Image URL (metadata reference only)
        <input
          aria-label="Token image URL"
          value={draft.image}
          maxLength={2048}
          onChange={(e) => field("image", e.target.value)}
          placeholder="https://…"
        />
      </label>
    </>
  );
  return (
    <section className="tool-page">
      <header className="tool-heading">
        <div>
          <small>CREATE / SOLANA MAINNET</small>
          <h1>
            {kind === "launch"
              ? "Launchpad"
              : kind === "tweet"
                ? "Tweet to Token"
                : "Website Builder"}
          </h1>
          <p>
            {kind === "launch"
              ? "Prepare and review an SPL token draft. Live deployment is disabled."
              : kind === "tweet"
                ? "Paste public text, create an editable concept, then continue to Launchpad."
                : "Build an editable page, preview in isolation and download safe HTML."}
          </p>
        </div>
      </header>
      {kind === "launch" && (
        <>
          <div className="wizard-steps">
            {["Metadata", "Supply & permissions", "Review & export"].map(
              (s, i) => (
                <span key={s} className={step === i ? "selected" : ""}>
                  {i + 1}. {s}
                </span>
              ),
            )}
          </div>
          <div className="tool-form">
            {step === 0 && metadata}
            {step === 1 && (
              <>
                <label>
                  Proposed supply
                  <input
                    aria-label="Token supply"
                    value={draft.supply}
                    maxLength={30}
                    inputMode="decimal"
                    onChange={(e) => field("supply", e.target.value)}
                  />
                </label>
                <label>
                  Decimals
                  <select
                    aria-label="Token decimals"
                    value={draft.decimals}
                    onChange={(e) => field("decimals", Number(e.target.value))}
                  >
                    {[0, 2, 6, 9].map((n) => (
                      <option key={n} value={n}>
                        {n}
                      </option>
                    ))}
                  </select>
                </label>
                <label className="check-label">
                  <input
                    type="checkbox"
                    checked={draft.mintAuthority}
                    onChange={(e) => field("mintAuthority", e.target.checked)}
                  />{" "}
                  Retain mint authority (owner can issue more tokens)
                </label>
                <label className="check-label">
                  <input
                    type="checkbox"
                    checked={draft.freezeAuthority}
                    onChange={(e) => field("freezeAuthority", e.target.checked)}
                  />{" "}
                  Retain freeze authority (owner can freeze token accounts)
                </label>
                <p className="data-note">
                  Revoking an authority is permanent on-chain. SPL holders can
                  burn tokens they own. Metadata immutability and rent/fee
                  estimates require a verified deployment implementation.
                </p>
              </>
            )}
            {step === 2 && (
              <>
                <dl className="draft-review">
                  <dt>Network</dt>
                  <dd>Solana mainnet</dd>
                  <dt>Standard</dt>
                  <dd>SPL Token</dd>
                  <dt>Name / ticker</dt>
                  <dd>
                    {draft.name} / {draft.symbol}
                  </dd>
                  <dt>Proposed supply</dt>
                  <dd>
                    {draft.supply} · {draft.decimals} decimals
                  </dd>
                  <dt>Mint authority</dt>
                  <dd>
                    {draft.mintAuthority
                      ? "Retained in proposal"
                      : "Proposed revocation"}
                  </dd>
                  <dt>Freeze authority</dt>
                  <dd>
                    {draft.freezeAuthority
                      ? "Retained in proposal"
                      : "Proposed revocation"}
                  </dd>
                  <dt>Rent + network fee</dt>
                  <dd>Unavailable until deployment adapter is verified</dd>
                  <dt>Transaction / mint</dt>
                  <dd>Not prepared / not deployed</dd>
                </dl>
                <button disabled className="primary-action">
                  Deploy unavailable
                </button>
                <p className="data-note">
                  A verified SPL deployment, metadata upload and wallet
                  confirmation path is not configured. Export a reviewable
                  draft; it is not a transaction. No funds move.
                </p>
                <button
                  onClick={() => {
                    try {
                      const amount = draftAmount(draft);
                      downloadFile(
                        "part-solana-token-draft.json",
                        JSON.stringify(
                          {
                            ...draft,
                            network: "solana-mainnet",
                            standard: "SPL Token",
                            baseUnitSupply: String(amount),
                            status: "draft-only",
                            transaction: null,
                          },
                          null,
                          2,
                        ),
                        "application/json",
                      );
                    } catch (e) {
                      setError(errorMessage(e));
                    }
                  }}
                >
                  Export reviewed draft
                </button>
                <button onClick={() => open("website")}>
                  Continue to Website Builder
                </button>
              </>
            )}
            <div className="tool-actions">
              {step > 0 && (
                <button
                  onClick={() => {
                    setStep((s) => s - 1);
                    setError("");
                  }}
                >
                  Back
                </button>
              )}
              {step < 2 && (
                <button
                  className="primary-action"
                  onClick={() => {
                    try {
                      if (
                        step === 0 &&
                        (!draft.name.trim() ||
                          !/^[A-Za-z0-9_$-]{1,10}$/.test(draft.symbol))
                      )
                        throw new Error(
                          "Enter a name and a 1–10 character ticker.",
                        );
                      if (step === 1) draftAmount(draft);
                      setStep((s) => s + 1);
                      setError("");
                    } catch (e) {
                      setError(errorMessage(e));
                    }
                  }}
                >
                  Continue
                </button>
              )}
            </div>
          </div>
        </>
      )}
      {kind !== "launch" && (
        <>
          <div className="tool-form">
            <label>
              {kind === "tweet"
                ? "Exact pasted public post (URL retrieval is not connected)"
                : "Page idea / creative direction"}
              <textarea
                aria-label={kind === "tweet" ? "Tweet text" : "Website idea"}
                value={text}
                maxLength={3000}
                onChange={(e) => setText(e.target.value)}
              />
            </label>
            <div className="tool-actions">
              <button
                className="primary-action"
                disabled={busy || !text.trim()}
                onClick={() => void generate()}
              >
                {busy ? "Generating…" : "Generate with Astra"}
              </button>
              {busy && (
                <button onClick={() => abort.current?.abort()}>
                  Stop generating
                </button>
              )}
            </div>
            {metadata}
            <label>
              Story
              <textarea
                aria-label="Token story"
                value={draft.story}
                maxLength={3000}
                onChange={(e) => field("story", e.target.value)}
              />
            </label>
            <label>
              Social post draft
              <textarea
                aria-label="Social post draft"
                value={draft.socialPost}
                maxLength={500}
                onChange={(e) => field("socialPost", e.target.value)}
              />
            </label>
          </div>
          {kind === "tweet" ? (
            <>
              <div
                className="concept-monogram"
                aria-label="Text concept preview"
              >
                {draft.symbol || "SPL"}
              </div>
              <p className="data-note">
                Text preview only. AI image generation and public post retrieval
                are not connected. Review rights and avoid impersonation.
              </p>
              <button
                className="primary-action"
                onClick={() => {
                  storeDraft(draft);
                  open("launch");
                }}
              >
                Continue to Launchpad
              </button>
            </>
          ) : (
            <>
              <div className="tool-actions">
                <button
                  onClick={() => {
                    const html = websiteTemplate(draft, text);
                    setSource(html);
                    setPreview(sanitizePreview(html));
                  }}
                >
                  Build from current draft
                </button>
                <button
                  onClick={() => {
                    setPreview(sanitizePreview(source));
                    setNotice(
                      "Preview updated. Scripts, custom CSS, embeds and unsafe attributes are removed.",
                    );
                  }}
                >
                  Update safe preview
                </button>
                <button
                  onClick={() => {
                    void navigator.clipboard
                      .writeText(sanitizePreview(source))
                      .then(() => setNotice("Safe HTML copied."))
                      .catch(() => setError("Clipboard unavailable."));
                  }}
                >
                  Copy HTML
                </button>
                <button
                  onClick={() =>
                    downloadFile(
                      "solana-project.html",
                      sanitizePreview(source),
                      "text/html",
                    )
                  }
                >
                  Download HTML
                </button>
              </div>
              <label className="source-label">
                Editable HTML source (100 KB limit)
                <textarea
                  aria-label="Website HTML source"
                  className="code-editor"
                  spellCheck={false}
                  maxLength={100000}
                  value={source}
                  onChange={(e) => setSource(e.target.value)}
                />
              </label>
              <iframe
                title="Isolated website preview"
                sandbox=""
                referrerPolicy="no-referrer"
                srcDoc={preview}
                className="website-preview"
              />
              <p className="data-note">
                Preview and export use an allowlist of text/layout tags, HTTPS
                links and fixed local styling. Scripts, external requests,
                forms, custom CSS and embeds are removed. Hosting is not
                connected; downloading does not publish the site.
              </p>
            </>
          )}
        </>
      )}
      {error && (
        <p role="alert" className="tool-error">
          {error}
        </p>
      )}
      {notice && <p role="status">{notice}</p>}
      <p className="tool-disclaimer">
        Drafts are stored only in this browser. Content is sent to the
        configured Astra backend only when Generate is pressed. No wallet
        secrets or automatic signatures.
      </p>
    </section>
  );
}
